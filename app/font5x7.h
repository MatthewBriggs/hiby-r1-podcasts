/* font5x7.h — minimal 5x7 bitmap font, uppercase + digits + punctuation.
 *
 * Each glyph is 7 rows; the low 5 bits of each byte are the pixels, MSB of the
 * five on the left. Lowercase is folded to uppercase by the lookup. Enough to
 * label a list; not a general text engine.
 */
