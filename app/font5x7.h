/* A few symbols that turn up in feed and episode names. */
static const uint8_t FONT_DASH[7]   = {0x00,0x00,0x00,0x1F,0x00,0x00,0x00};
static const uint8_t FONT_DOT[7]    = {0x00,0x00,0x00,0x00,0x00,0x0C,0x0C};
static const uint8_t FONT_COLON[7]  = {0x00,0x0C,0x0C,0x00,0x0C,0x0C,0x00};
static const uint8_t FONT_SLASH[7]  = {0x01,0x02,0x02,0x04,0x08,0x08,0x10};
static const uint8_t FONT_LPAR[7]   = {0x02,0x04,0x08,0x08,0x08,0x04,0x02};
static const uint8_t FONT_RPAR[7]   = {0x08,0x04,0x02,0x02,0x02,0x04,0x08};
static const uint8_t FONT_AMP[7]    = {0x0C,0x12,0x14,0x08,0x15,0x12,0x0D};
static const uint8_t FONT_QUERY[7]  = {0x0E,0x11,0x01,0x02,0x04,0x00,0x04};
static const uint8_t FONT_EXCL[7]   = {0x04,0x04,0x04,0x04,0x04,0x00,0x04};
static const uint8_t FONT_UNK[7]    = {0x1F,0x11,0x11,0x11,0x11,0x11,0x1F};

static const uint8_t *glyph_for(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return FONT_AZ[c - 'A'];
    if (c >= '0' && c <= '9') return FONT_09[c - '0'];
    switch (c) {
        case ' ': return FONT_SPACE;
        case '-': case '_': return FONT_DASH;
        case '.': case ',': return FONT_DOT;
        case ':': case ';': return FONT_COLON;
        case '/': case '\\': return FONT_SLASH;
        case '(': case '[': return FONT_LPAR;
        case ')': case ']': return FONT_RPAR;
        case '&': case '+': return FONT_AMP;
        case '?': return FONT_QUERY;
        case '!': return FONT_EXCL;
        default: return FONT_UNK;
    }
}

